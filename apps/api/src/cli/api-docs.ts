/**
 * Generates docs/api.md from the live route table: every endpoint with its
 * HTTP method and required permission.  Run: npm run docs:api -w @taskora/api
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildApp } from '../app.js';
import { loadConfig } from '../config.js';
import type { Db } from '../db/client.js';

const app = await buildApp({ db: {} as Db, config: loadConfig({ NODE_ENV: 'test', LOG_LEVEL: 'silent' }), logger: false });
await app.ready();

const groups = new Map<string, typeof app.routeCatalog>();
for (const r of app.routeCatalog.filter((x) => x.url.startsWith('/api')).sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method))) {
  const seg = r.url.replace('/api/v1/', '').split('/')[0] || 'health';
  const key = seg.startsWith('/api') ? 'health' : seg;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key)!.push(r);
}

const lines = [
  '# Taskora REST API',
  '',
  '_Generated by `npm run docs:api -w @taskora/api` — do not edit by hand._',
  '',
  '## Conventions',
  '',
  '- Base path: `/api/v1`, JSON request and response bodies.',
  '- Authentication: session cookie `taskora_session` obtained from `POST /api/v1/auth/login` (`{ email, password }`). The response contains a `csrfToken`; send it as the `X-CSRF-Token` header on every POST/PUT/PATCH/DELETE.',
  '- Authorization: each endpoint requires the listed permission (roles are managed in Administration → Users & Roles). Endpoints without a permission require any signed-in user; `public` endpoints need no session.',
  '- Lists: `?page=1&pageSize=50&sort=<field>&order=asc|desc&q=<search>` plus module filters; responses are `{ data, total, page, pageSize }`.',
  '- Errors: `{ error: { code, message, details?: { fields } } }` with HTTP 400 (validation), 401, 403, 404, 409 (duplicate / in use), 423 (locked account), 500.',
  '- Request bodies are validated with the Zod schemas in `packages/shared/src/schemas.ts`.',
  '',
];
for (const [group, routes] of groups) {
  lines.push(`## ${group}`, '', '| Method | Path | Permission |', '| --- | --- | --- |');
  for (const r of routes) lines.push(`| ${r.method} | \`${r.url}\` | ${r.public ? 'public' : r.perm ? `\`${r.perm}\`` : 'signed in'} |`);
  lines.push('');
}
const out = resolve(process.cwd(), process.argv[2] ?? '../../docs/api.md');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${app.routeCatalog.length} routes to ${out}`);
await app.close();
